import logging
import re
from datetime import datetime, timedelta, timezone
from uuid import UUID

logger = logging.getLogger("workpilot.tickets")

PRIORITIES = ("low", "medium", "high", "critical")
STATUSES = ("open", "in_progress", "resolved", "closed")
COLUMNS = "id,ticket_number,title,description,category,priority,status,created_at,updated_at"
UPDATABLE = ("title", "description", "status", "priority")  # nothing else can be changed by clients
DUPLICATE_WINDOW_SECONDS = 60  # identical ticket within this window = accidental repeat

_TICKET_NUMBER = re.compile(r"^TKT-\d+$")


class TicketError(Exception):
    def __init__(self, message: str, status_code: int = 500):
        super().__init__(message)
        self.status_code = status_code


def _db(db):
    if db is None:
        from app.core.database import get_supabase

        db = get_supabase()
    return db


def create_ticket(data: dict, *, db=None) -> tuple[dict, bool]:
    """Insert a ticket. Returns (ticket, created).

    ticket_number and id are generated by the database. If an identical ticket was created
    within DUPLICATE_WINDOW_SECONDS, that ticket is returned with created=False instead.
    """
    title = (data.get("title") or "").strip()
    if not title:
        raise TicketError("Title is required.", 422)
    row = {
        "title": title,
        "description": (data.get("description") or "").strip(),
        "category": (data.get("category") or "general").strip().lower() or "general",
        "priority": data.get("priority") or "medium",
    }
    if row["priority"] not in PRIORITIES:
        raise TicketError(f"Priority must be one of: {', '.join(PRIORITIES)}.", 422)

    db = _db(db)
    try:
        cutoff = (datetime.now(timezone.utc) - timedelta(seconds=DUPLICATE_WINDOW_SECONDS)).isoformat()
        query = db.table("tickets").select(COLUMNS)
        for key, value in row.items():
            query = query.eq(key, value)
        recent = query.gte("created_at", cutoff).limit(1).execute().data
        if recent:
            return recent[0], False
        inserted = db.table("tickets").insert(row).execute().data
    except Exception:
        logger.exception("Could not create ticket")
        raise TicketError("Could not create the ticket.", 500) from None
    if not inserted:
        raise TicketError("Could not create the ticket.", 500)
    return inserted[0], True


def list_tickets(*, status=None, priority=None, limit: int = 50, offset: int = 0, db=None) -> dict:
    db = _db(db)
    try:
        query = db.table("tickets").select(COLUMNS)
        if status:
            query = query.eq("status", status)
        if priority:
            query = query.eq("priority", priority)
        rows = query.order("created_at", desc=True).range(offset, offset + limit - 1).execute().data or []
    except Exception:
        logger.exception("Could not list tickets")
        raise TicketError("Could not list tickets.", 500) from None
    return {"tickets": rows, "count": len(rows), "limit": limit, "offset": offset}


def _lookup(identifier: str) -> tuple[str, str]:
    """Accept a ticket UUID or a ticket number such as TKT-1001."""
    ident = (identifier or "").strip()
    try:
        return "id", str(UUID(ident))
    except ValueError:
        pass
    if _TICKET_NUMBER.match(ident.upper()):
        return "ticket_number", ident.upper()
    raise TicketError("Invalid ticket identifier. Use the ticket UUID or a number like TKT-1001.", 422)


def get_ticket(identifier: str, *, db=None) -> dict:
    column, value = _lookup(identifier)
    db = _db(db)
    try:
        rows = db.table("tickets").select(COLUMNS).eq(column, value).limit(1).execute().data
    except Exception:
        logger.exception("Could not fetch ticket")
        raise TicketError("Could not fetch the ticket.", 500) from None
    if not rows:
        raise TicketError("Ticket not found.", 404)
    return rows[0]


def update_ticket(identifier: str, data: dict, *, db=None) -> dict:
    """Update only the supplied fields among title, description, status, priority."""
    changes = {k: v for k, v in data.items() if k in UPDATABLE and v is not None}
    for key in ("title", "description"):
        if key in changes:
            changes[key] = changes[key].strip()
    if "title" in changes and not changes["title"]:
        raise TicketError("Title must not be blank.", 422)
    if "status" in changes and changes["status"] not in STATUSES:
        raise TicketError(f"Status must be one of: {', '.join(STATUSES)}.", 422)
    if "priority" in changes and changes["priority"] not in PRIORITIES:
        raise TicketError(f"Priority must be one of: {', '.join(PRIORITIES)}.", 422)
    if not changes:
        raise TicketError("No updatable fields supplied (title, description, status, priority).", 422)

    column, value = _lookup(identifier)
    db = _db(db)
    try:
        rows = db.table("tickets").update(changes).eq(column, value).execute().data  # updated_at set by trigger
    except Exception:
        logger.exception("Could not update ticket")
        raise TicketError("Could not update the ticket.", 500) from None
    if not rows:
        raise TicketError("Ticket not found.", 404)
    return rows[0]
